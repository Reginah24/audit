// The built-in PDF font only covers basic Latin characters, so the text in
// here sticks to plain hyphens and quotes rather than dashes and bullets.

const _ink = PdfColor.fromInt(0xFF1E2A26);
const _muted = PdfColor.fromInt(0xFF5E655F);
const _accent = PdfColor.fromInt(0xFF2E5A4B);
const _band = PdfColor.fromInt(0xFFF5F1EA);

/// Opens the system print / save-as-PDF dialog.
Future<void> printPdf(Uint8List bytes, String name) =>
    Printing.layoutPdf(onLayout: (_) async => bytes, name: name);

/// Opens the share sheet (email, WhatsApp, Drive…) on phones and tablets;
/// downloads the file in a web browser.
Future<void> sharePdf(Uint8List bytes, String filename) =>
    Printing.sharePdf(bytes: bytes, filename: filename);

pw.Widget _header(String title, String subtitle) {
  return pw.Column(
    crossAxisAlignment: pw.CrossAxisAlignment.start,
    children: [
      pw.Text(officeName.toUpperCase(),
          style: const pw.TextStyle(fontSize: 9, color: _muted)),
      pw.SizedBox(height: 4),
      pw.Text(title,
          style: const pw.TextStyle(
              fontSize: 20, fontWeight: pw.FontWeight.bold, color: _ink)),
      pw.SizedBox(height: 2),
      pw.Text(subtitle, style: const pw.TextStyle(fontSize: 11, color: _muted)),
      pw.SizedBox(height: 4),
      pw.Divider(color: _accent, thickness: 2),
      pw.SizedBox(height: 8),
    ],
  );
}

pw.Widget _footer(pw.Context context) {
  final generated = DateFormat('d MMM yyyy, HH:mm').format(DateTime.now());
  return pw.Row(
    mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
    children: [
      pw.Text('Generated by $restaurantName on $generated',
          style: const pw.TextStyle(fontSize: 8, color: _muted)),
      pw.Text('Page ${context.pageNumber} of ${context.pagesCount}',
          style: const pw.TextStyle(fontSize: 8, color: _muted)),
    ],
  );
}

pw.Widget _stat(String label, int value) {
  return pw.Expanded(
    child: pw.Container(
      height: 58,
      margin: const pw.EdgeInsets.only(right: 6),
      padding: const pw.EdgeInsets.all(8),
      decoration: const pw.BoxDecoration(color: _band),
      child: pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Text('$value',
              style: const pw.TextStyle(
                  fontSize: 18, fontWeight: pw.FontWeight.bold, color: _ink)),
          pw.Text(label, style: const pw.TextStyle(fontSize: 8, color: _muted)),
        ],
      ),
    ),
  );
}

pw.Widget _table(List<String> headers, List<List<String>> rows,
    {Map<int, pw.TableColumnWidth>? widths}) {
  return pw.TableHelper.fromTextArray(
    headers: headers,
    data: rows,
    columnWidths: widths,
    headerStyle: const pw.TextStyle(
        fontSize: 9, fontWeight: pw.FontWeight.bold, color: PdfColors.white),
    headerDecoration: const pw.BoxDecoration(color: _ink),
    cellStyle: const pw.TextStyle(fontSize: 9, color: _ink),
    oddRowDecoration: const pw.BoxDecoration(color: _band),
    cellPadding: const pw.EdgeInsets.symmetric(horizontal: 5, vertical: 4),
    border: null,
  );
}

Future<Uint8List> buildDayReportPdf(
    DayReport report, List<GuestMeal> guests) async {
  final day = parseDateKey(report.date);
  final doc = pw.Document(title: 'Meal report ${report.date}');

  doc.addPage(pw.MultiPage(
    pageFormat: PdfPageFormat.a4,
    margin: const pw.EdgeInsets.all(32),
    header: (_) => _header('Daily meal report',
        '${DateFormat('EEEE d MMMM yyyy').format(day)} - $restaurantName'),
    footer: _footer,
    build: (_) => [
      ..._daySummarySection(report, guests),
      ..._correctionsSection(report.corrections),
      pw.SizedBox(height: 30),
      _signatureLines(),
    ],
  ));

  return doc.save();
}

Future<Uint8List> buildMonthReportPdf(
    DateTime month, MonthReport report, int guestMeals) async {
  final doc =
      pw.Document(title: 'Meal report ${DateFormat('yyyy-MM').format(month)}');

  doc.addPage(pw.MultiPage(
    pageFormat: PdfPageFormat.a4,
    margin: const pw.EdgeInsets.all(32),
    header: (_) => _header('Monthly meal report',
        '${DateFormat('MMMM yyyy').format(month)} - $restaurantName'),
    footer: _footer,
    build: (_) => [
      pw.Row(children: [
        _stat('Days served', report.days.length),
        _stat('Meals eaten', report.totalMeals),
        _stat('Guest meals', guestMeals),
        _stat('Meals booked', report.totalBooked),
        _stat('Booked, not eaten', report.totalNoShows),
        _stat('Corrections', report.corrections.length),
      ]),
      pw.SizedBox(height: 14),
      pw.Text('Per employee',
          style:
              const pw.TextStyle(fontWeight: pw.FontWeight.bold, color: _ink)),
      pw.SizedBox(height: 6),
      _table(
        [
          '#',
          'Name',
          'Department',
          'Meals eaten',
          'Days booked',
          'Booked, not eaten',
          'Ate, not booked'
        ],
        [
          for (var i = 0; i < report.rows.length; i++)
            [
              '${i + 1}',
              report.rows[i].employee.name,
              report.rows[i].employee.department,
              '${report.rows[i].meals}',
              '${report.rows[i].booked}',
              '${report.rows[i].noShows}',
              '${report.rows[i].unplanned}',
            ],
          [
            '',
            'TOTAL',
            '',
            '${report.totalMeals}',
            '${report.totalBooked}',
            '${report.totalNoShows}',
            '${report.totalUnplanned}'
          ],
        ],
        widths: const {
          0: pw.FixedColumnWidth(22),
          1: pw.FlexColumnWidth(3),
          2: pw.FlexColumnWidth(2),
          3: pw.FlexColumnWidth(1.2),
          4: pw.FlexColumnWidth(1.2),
          5: pw.FlexColumnWidth(1.4),
          6: pw.FlexColumnWidth(1.4),
        },
      ),
      pw.SizedBox(height: 18),
      pw.Text('Per day',
          style:
              const pw.TextStyle(fontWeight: pw.FontWeight.bold, color: _ink)),
      pw.SizedBox(height: 6),
      _table(
        ['Date', 'Booked', 'Ate'],
        [
          for (final d in report.days)
            [
              DateFormat('EEE d MMM').format(parseDateKey(d.date)),
              '${d.booked}',
              '${d.ate}',
            ],
        ],
      ),
      ..._addedSection(report.added),
      ..._correctionsSection(report.corrections),
      pw.SizedBox(height: 30),
      _signatureLines(),
    ],
  ));

  return doc.save();
}

/// The day as the office writes it: the total who ate (staff and guests),
/// then each exception with its names and count. Nobody else is listed.
List<pw.Widget> _daySummarySection(DayReport report, List<GuestMeal> guests) {
  final groups = [
    ('Not on the list, but came', report.rows.where((r) => r.ateUnregistered)),
    (
      'Had blue (said they would not come), but came',
      report.rows.where((r) => r.ateSaidNo)
    ),
    ('Registered but did not come', report.rows.where((r) => r.noShow)),
  ];
  const bold = pw.TextStyle(fontWeight: pw.FontWeight.bold, color: _ink);
  return [
    pw.Text('Total who ate: ${report.ate + guests.length}',
        style: const pw.TextStyle(
            fontSize: 16, fontWeight: pw.FontWeight.bold, color: _ink)),
    pw.Text('Staff ${report.ate} + guests ${guests.length}',
        style: const pw.TextStyle(fontSize: 10, color: _muted)),
    pw.SizedBox(height: 16),
    for (final (title, rows) in groups) ...[
      pw.Text('$title: ${rows.length}', style: bold),
      pw.SizedBox(height: 3),
      if (rows.isEmpty)
        pw.Text('None.', style: const pw.TextStyle(fontSize: 9, color: _muted))
      else
        for (final (i, r) in rows.indexed)
          pw.Text(
              '${i + 1}. ${r.employee.name}'
              '${r.employee.department.isEmpty ? '' : ' (${r.employee.department})'}',
              style: const pw.TextStyle(fontSize: 10, color: _ink)),
      pw.SizedBox(height: 12),
    ],
    pw.Text('Guests: ${guests.length}', style: bold),
    pw.SizedBox(height: 3),
    if (guests.isEmpty)
      pw.Text('None.', style: const pw.TextStyle(fontSize: 9, color: _muted))
    else
      for (final (i, g) in guests.indexed)
        pw.Text('${i + 1}. ${g.name}${g.note.isEmpty ? '' : ' (${g.note})'}',
            style: const pw.TextStyle(fontSize: 10, color: _ink)),
  ];
}

/// People added at the restaurant counter (not on the office's list).
/// Always printed, even when empty, so the office can see there were none.
List<pw.Widget> _addedSection(List<Employee> added) {
  return [
    pw.SizedBox(height: 18),
    pw.Text('People added at the restaurant counter (not on the office list)',
        style: const pw.TextStyle(fontWeight: pw.FontWeight.bold, color: _ink)),
    pw.SizedBox(height: 6),
    if (added.isEmpty)
      pw.Text('None.', style: const pw.TextStyle(fontSize: 9, color: _muted))
    else
      _table(
        ['Name', 'Department', 'Added', 'Added by'],
        [
          for (final e in added)
            [
              e.name,
              e.department,
              DateFormat('d MMM HH:mm').format(e.addedAt!),
              e.addedBy ?? '',
            ],
        ],
      ),
  ];
}

/// Every meal the restaurant removed, with who, when and why. Always
/// printed (even when empty) so the office can see there were none.
List<pw.Widget> _correctionsSection(List<VoidedCheckIn> corrections) {
  String time(Timestamp t) => DateFormat('d MMM HH:mm').format(t.toDate());
  return [
    pw.SizedBox(height: 18),
    pw.Text('Corrections (meals removed by the restaurant)',
        style: const pw.TextStyle(fontWeight: pw.FontWeight.bold, color: _ink)),
    pw.SizedBox(height: 6),
    if (corrections.isEmpty)
      pw.Text('None.', style: const pw.TextStyle(fontSize: 9, color: _muted))
    else
      _table(
        ['Name', 'Recorded', 'Removed', 'Removed by', 'Reason'],
        [
          for (final c in corrections)
            [
              c.original.employeeName,
              time(c.original.timestamp),
              time(c.voidedAt),
              c.voidedBy,
              c.reason,
            ],
        ],
      ),
  ];
}

pw.Widget _signatureLines() {
  pw.Widget line(String label) => pw.Expanded(
        child: pw.Column(
          crossAxisAlignment: pw.CrossAxisAlignment.start,
          children: [
            pw.SizedBox(height: 28),
            pw.Container(height: 0.8, color: _ink),
            pw.SizedBox(height: 3),
            pw.Text(label,
                style: const pw.TextStyle(fontSize: 8, color: _muted)),
          ],
        ),
      );
  return pw.Row(children: [
    line('Prepared by ($restaurantName) - name, signature, date'),
    pw.SizedBox(width: 30),
    line('Received by ($officeName) - name, signature, date'),
  ]);
}

/// One card per employee with a QR code, eight to an A4 page. Print on
/// card stock, cut along the borders, and laminate if possible.
Future<Uint8List> buildBadgesPdf(
    List<Employee> employees, Map<String, String> badgeKeys) async {
  final doc = pw.Document(title: 'Meal passes');
  const perPage = 8;

  for (var start = 0; start < employees.length; start += perPage) {
    final page = employees.skip(start).take(perPage).toList();
    doc.addPage(pw.Page(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(24),
      build: (_) => pw.GridView(
        crossAxisCount: 2,
        // pdf's GridView takes height / width; this fits four rows on A4.
        childAspectRatio: 0.7,
        children: [for (final e in page) _badge(e, badgeKeys[e.id] ?? '')],
      ),
    ));
  }

  return doc.save();
}

pw.Widget _badge(Employee e, String key) {
  return pw.Container(
    margin: const pw.EdgeInsets.all(4),
    padding: const pw.EdgeInsets.all(10),
    decoration: pw.BoxDecoration(
      border: pw.Border.all(
          color: _muted, width: 0.6, style: pw.BorderStyle.dashed),
    ),
    child: pw.Row(
      children: [
        pw.BarcodeWidget(
          barcode: pw.Barcode.qrCode(),
          data: badgeCodeFor(e.id, key),
          width: 120,
          height: 120,
        ),
        pw.SizedBox(width: 12),
        pw.Expanded(
          child: pw.Column(
            mainAxisAlignment: pw.MainAxisAlignment.center,
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Text('MEAL PASS',
                  style: const pw.TextStyle(
                      fontSize: 8,
                      color: _accent,
                      fontWeight: pw.FontWeight.bold)),
              pw.SizedBox(height: 6),
              pw.Text(e.name,
                  style: const pw.TextStyle(
                      fontSize: 15,
                      fontWeight: pw.FontWeight.bold,
                      color: _ink)),
              pw.SizedBox(height: 3),
              pw.Text(e.department,
                  style: const pw.TextStyle(fontSize: 10, color: _muted)),
              pw.SizedBox(height: 10),
              pw.Text('Scan on arrival at the restaurant',
                  style: const pw.TextStyle(fontSize: 8, color: _muted)),
            ],
          ),
        ),
      ],
    ),
  );
}
